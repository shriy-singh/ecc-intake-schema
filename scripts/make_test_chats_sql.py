"""Generate sql/test_chats.sql: the 40-chat test set as a Supabase table.

Blank CSV cells become NULL, which avoids Supabase's CSV importer rejecting
empty strings in boolean/timestamp columns.

    python scripts/make_test_chats_sql.py [path/to/test_set.csv]
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CSV = ROOT / "data" / "palantir_ecc_intake_test_set_40_chats.csv"
OUT = ROOT / "sql" / "test_chats.sql"

COLUMN_TYPES = {
    "chat_id": "text not null",
    "turn_number": "integer not null",
    "resident_message": "text not null",
    "chat_label": "text not null check (chat_label in ('routine', 'handoff'))",
    "expected_outcome": "text not null",
    "expected_request_type": "text",
    "expected_handoff_trigger": "text",
    "expected_location": "text",
    "expected_noise_source": "text",
    "expected_vehicle_description": "text",
    "expected_license_plate": "text",
    "expected_blocking_driveway": "boolean",
    "expected_pothole_size": "text",
    "expected_hazard_to_traffic": "boolean",
    "expected_callback_phone": "text",
    "incident_observed_at": "timestamptz",
    "source_call_date": "date",
}


def sql_literal(value: str, column: str) -> str:
    if value.strip() == "":
        return "null"
    if COLUMN_TYPES[column].startswith("integer"):
        return str(int(value))
    if COLUMN_TYPES[column] == "boolean":
        return {"true": "true", "false": "false"}[value.strip().lower()]
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    csv_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CSV
    with csv_path.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        if list(reader.fieldnames) != list(COLUMN_TYPES):
            sys.exit(f"CSV columns don't match expected test-set columns: {reader.fieldnames}")
        rows = list(reader)

    columns = list(COLUMN_TYPES)
    lines = [
        "-- ECC intake test set: 40 labeled chats, one row per resident turn.",
        f"-- Generated by scripts/make_test_chats_sql.py from {csv_path.name}; do not edit by hand.",
        "",
        "create table if not exists public.test_chats (",
        *(f"  {name:<29} {ctype}," for name, ctype in COLUMN_TYPES.items()),
        "  primary key (chat_id, turn_number)",
        ");",
        "",
        "alter table public.test_chats enable row level security;",
        "",
        f"insert into public.test_chats ({', '.join(columns)}) values",
    ]
    values = [
        "  (" + ", ".join(sql_literal(row[c], c) for c in columns) + ")" for row in rows
    ]
    lines.append(",\n".join(values))
    lines.append("on conflict (chat_id, turn_number) do nothing;")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} rows to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
